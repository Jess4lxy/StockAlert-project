-- StockAlert - esquema de base de datos (PostgreSQL)
--
-- Recrea todas las tablas desde cero. Usar solo en entornos de desarrollo y
-- pruebas: borra los datos existentes.
--
-- No se definen índices secundarios a propósito: solo existen los que crean
-- las llaves primarias y las restricciones UNIQUE. Así se obtiene la línea base
-- para medir el rendimiento antes de optimizar (Tarea 3).

DROP TABLE IF EXISTS alertas;
DROP TABLE IF EXISTS movimientos;
DROP TABLE IF EXISTS productos;
DROP TABLE IF EXISTS usuarios;

CREATE TABLE usuarios (
    id_usuario       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre           VARCHAR(100) NOT NULL,
    correo           VARCHAR(150) NOT NULL UNIQUE,
    contrasena_hash  TEXT         NOT NULL,
    rol              VARCHAR(30)  NOT NULL CHECK (rol IN ('admin', 'almacen')),
    fecha_registro   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    estado           BOOLEAN      NOT NULL DEFAULT true
);

CREATE TABLE productos (
    id_producto          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre               VARCHAR(150)  NOT NULL,
    descripcion          TEXT,
    categoria            VARCHAR(80),
    stock_actual         INTEGER       NOT NULL DEFAULT 0 CHECK (stock_actual >= 0),
    stock_minimo         INTEGER       NOT NULL DEFAULT 0 CHECK (stock_minimo >= 0),
    precio               NUMERIC(12,2) NOT NULL CHECK (precio >= 0),
    fecha_actualizacion  TIMESTAMPTZ   NOT NULL DEFAULT now(),
    estado               BOOLEAN       NOT NULL DEFAULT true
);

CREATE TABLE movimientos (
    id_movimiento     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto       INTEGER      NOT NULL REFERENCES productos (id_producto),
    id_usuario        INTEGER      NOT NULL REFERENCES usuarios (id_usuario),
    tipo_movimiento   VARCHAR(20)  NOT NULL CHECK (tipo_movimiento IN ('entrada', 'salida', 'ajuste')),
    -- entradas y salidas siempre positivas; un ajuste puede sumar o restar
    cantidad          INTEGER      NOT NULL CHECK (
                          (tipo_movimiento = 'ajuste' AND cantidad <> 0)
                          OR (tipo_movimiento <> 'ajuste' AND cantidad > 0)
                      ),
    fecha_movimiento  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    observaciones     TEXT
);

CREATE TABLE alertas (
    id_alerta         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto       INTEGER      NOT NULL REFERENCES productos (id_producto),
    tipo_alerta       VARCHAR(30)  NOT NULL CHECK (tipo_alerta IN ('stock_bajo', 'agotado')),
    stock_detectado   INTEGER      NOT NULL CHECK (stock_detectado >= 0),
    fecha_generacion  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    estado            VARCHAR(20)  NOT NULL DEFAULT 'pendiente'
                                   CHECK (estado IN ('pendiente', 'atendida', 'cerrada')),
    fecha_atencion    TIMESTAMPTZ
);
