-- StockAlert - migración 001: sesiones (refresh tokens) y solicitudes de reposición.
--
-- No borra nada: crea las tablas solo si no existen. Se aplica en una base con
-- datos con `npm run migrar` (etl/) y también al final de `npm run load`.

-- Refresh tokens. Solo se guarda el hash SHA-256 del token, nunca el token.
-- Cada inicio de sesión abre una "familia": al refrescar, el token usado se marca
-- (fecha_uso) y se emite otro de la misma familia. Si alguien presenta un token ya
-- usado, se revoca toda la familia (posible robo).
CREATE TABLE IF NOT EXISTS sesiones (
    id_sesion         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario        INTEGER      NOT NULL REFERENCES usuarios (id_usuario),
    familia           UUID         NOT NULL,
    token_hash        CHAR(64)     NOT NULL UNIQUE,
    -- web: el token viaja en una cookie httpOnly · movil: en el cuerpo JSON
    cliente           VARCHAR(10)  NOT NULL CHECK (cliente IN ('web', 'movil')),
    fecha_creacion    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_expiracion  TIMESTAMPTZ  NOT NULL,
    fecha_uso         TIMESTAMPTZ,
    fecha_revocacion  TIMESTAMPTZ
);
-- Cada petición autenticada revisa que su familia siga abierta, y cerrar sesión la revoca
CREATE INDEX IF NOT EXISTS sesiones_familia_idx ON sesiones (familia);

-- Solicitudes de reposición. Las registra el flujo de n8n al recibir una alerta
-- (una por alerta) y el equipo de la empresa les da seguimiento.
CREATE TABLE IF NOT EXISTS solicitudes_reposicion (
    id_solicitud         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto          INTEGER      NOT NULL REFERENCES productos (id_producto),
    id_alerta            BIGINT       UNIQUE REFERENCES alertas (id_alerta),
    cantidad_sugerida    INTEGER      NOT NULL CHECK (cantidad_sugerida > 0),
    estado               VARCHAR(20)  NOT NULL DEFAULT 'pendiente'
                                      CHECK (estado IN ('pendiente', 'pedida', 'recibida', 'cancelada')),
    notas                TEXT,
    fecha_creacion       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    fecha_actualizacion  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
